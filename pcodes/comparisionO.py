#comparision operators returns a boolean value
# == sign is used for checking equality and != is used for checking non-equality 
# ord() function is used to call the ascii value of a character 

bool_1=2<3
print(bool_1)    #this code will give True as output

bool_2= 4==3
print(bool_2)    #this code will give False as output since 4 is not equal to 3

bool_3= 4!=3
print(bool_3)    #this code will give True as output since we are checking non equality of 4 & 3

int_1=ord("a")
print(int_1)     #this code will give the ascii value of "a" which  is 97

