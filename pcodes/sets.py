#sets are made by {} just like in maths we can perform operations like union and intersection 
#as we know from maths elements are not repeated in sets
set_1={1,2,3,4,1,2,6,7,8,8}
set_2={1,4,8,9,2,3,5}

set_3= set_1 | set_2  #this will perform union
set_4= set_1 & set_2  #this will perform intersection
print(set_1)
print(set_3)
print(set_4)

# there is no indexing in sets 